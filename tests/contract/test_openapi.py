"""The published contract: the OpenAPI document itself.

Every other suite asks whether the service *behaves*. This one asks what it
*promises*, because the document is the artifact other teams build against —
`air-client` generates from it, and a path that quietly stops being declared
breaks a consumer long before it breaks a test here.

Three properties are pinned:

* **It generates at all.** ``app.openapi()`` walks every response model, and a
  model FastAPI cannot resolve raises at generation time rather than at import
  time. Nothing else in the suite would notice, because no other test asks for
  the document.
* **The surface is exactly docs/01-hld.md §4.** Nine paths under ``/v1``, with
  the methods that table gives them. Asserted as an equality rather than a
  series of ``in`` checks, so an accidentally exported route fails here too.
* **Failure is described, not only success.** A generated client that knows the
  200 shape and nothing else turns every error into an unparsed blob, so each
  analysis route has to declare its catalogue against ``ProblemDetail``.

The app is built without entering its lifespan: schema generation reads route
declarations, not runtime state, and no tier, cache or provider needs to exist
for it. That also keeps this suite free of sockets.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Final

import pytest
from fastapi import FastAPI

from air_classifier.config import (
    AppSettings,
    CacheSettings,
    OllamaSettings,
    ProvidersSettings,
    Settings,
)
from air_classifier.main import create_app

#: Where ``make openapi`` writes the spec. Regenerated by this suite so the
#: committed artifact cannot drift from the code that produces it — if it does,
#: the round-trip assertion below is what says so.
SPEC_PATH: Final[Path] = Path(__file__).resolve().parents[2] / "docs" / "openapi.json"

#: docs/01-hld.md §4, minus ``/metrics``: the exposition is line-oriented text
#: on a separate port, and declaring it here would describe it wrongly to every
#: generated client.
EXPECTED_PATHS: Final[dict[str, set[str]]] = {
    "/v1/sentiment": {"post"},
    "/v1/sentiment/batch": {"post"},
    "/v1/feedback": {"post"},
    "/v1/feedback/batch": {"post"},
    "/v1/reviews": {"post"},
    "/v1/reviews/batch": {"post"},
    "/v1/health": {"get"},
    "/v1/ready": {"get"},
    "/v1/capabilities": {"get"},
}

#: The six that run the ladder, and therefore carry the full error catalogue.
ANALYSIS_PATHS: Final[tuple[str, ...]] = (
    "/v1/sentiment",
    "/v1/sentiment/batch",
    "/v1/feedback",
    "/v1/feedback/batch",
    "/v1/reviews",
    "/v1/reviews/batch",
)

#: docs/02-lld.md §9. Every one of these is reachable on an analysis route, so
#: every one of them is declared.
EXPECTED_ERROR_STATUSES: Final[frozenset[str]] = frozenset(
    {"400", "401", "403", "409", "422", "429", "500", "503"}
)


@pytest.fixture(scope="module")
def app() -> FastAPI:
    """The real application, assembled but never started.

    Ollama off and no cloud credentials, so nothing in this module can be
    tempted to open a connection. Neither choice reaches the document: the
    routes are declared the same way whatever the ladder turns out to be.
    """
    return create_app(
        Settings(
            app=AppSettings(env="test"),
            providers=ProvidersSettings(ollama=OllamaSettings(enabled=False)),
            cache=CacheSettings(backend="memory"),
        )
    )


@pytest.fixture(scope="module")
def spec(app: FastAPI) -> dict[str, Any]:
    return app.openapi()


# ── The document ──────────────────────────────────────────────────────────────


def test_the_document_generates(spec: dict[str, Any]) -> None:
    """Generation is the assertion; a broken response model raises here."""
    assert spec["info"]["title"] == "AIR Classifier"
    assert spec["info"]["version"]
    assert spec["paths"]


def test_the_document_is_openapi_31(spec: dict[str, Any]) -> None:
    """3.1, not 3.0.

    Pinned because the two differ on things this API relies on: 3.1 aligns with
    JSON Schema proper, so nullable unions render as `anyOf` with `null` rather
    than 3.0's `nullable` extension — which is how `rating_consistency` and
    every other optional block are described.
    """
    assert spec["openapi"].startswith("3.1")


# ── Surface ───────────────────────────────────────────────────────────────────


#: Keys of a path item that are operations rather than metadata (`summary`,
#: `parameters`, `servers`, …).
_HTTP_METHODS: Final[frozenset[str]] = frozenset(
    {"get", "put", "post", "delete", "options", "head", "patch", "trace"}
)


def test_the_declared_surface_is_exactly_the_documented_one(spec: dict[str, Any]) -> None:
    declared = {
        path: {method for method in operations if method in _HTTP_METHODS}
        for path, operations in spec["paths"].items()
    }
    assert declared == EXPECTED_PATHS


def test_the_metrics_endpoint_is_not_advertised(spec: dict[str, Any]) -> None:
    """It exists and it is unauthenticated; it is simply not JSON.

    A generated client that found it here would type it as a JSON response and
    fail on the first scrape.
    """
    assert "/metrics" not in spec["paths"]


@pytest.mark.parametrize("path", ANALYSIS_PATHS)
def test_analysis_routes_declare_a_request_body(spec: dict[str, Any], path: str) -> None:
    operation = spec["paths"][path]["post"]
    content = operation["requestBody"]["content"]["application/json"]
    assert content["schema"]


# ── Errors ────────────────────────────────────────────────────────────────────


def test_problem_detail_is_a_component_schema(spec: dict[str, Any]) -> None:
    """One error model, referenced everywhere, so a client writes one parser."""
    schemas = spec["components"]["schemas"]
    assert "ProblemDetail" in schemas

    properties = schemas["ProblemDetail"]["properties"]
    # The RFC 9457 members, plus the two this service adds.
    assert {"type", "title", "status", "detail", "instance"} <= set(properties)
    assert {"request_id", "errors"} <= set(properties)


@pytest.mark.parametrize("path", ANALYSIS_PATHS)
def test_analysis_routes_declare_the_whole_error_catalogue(spec: dict[str, Any], path: str) -> None:
    responses = spec["paths"][path]["post"]["responses"]
    assert set(responses) >= EXPECTED_ERROR_STATUSES


@pytest.mark.parametrize("path", ANALYSIS_PATHS)
def test_every_declared_error_is_a_problem_detail(spec: dict[str, Any], path: str) -> None:
    """Not merely "an error is possible" — *this* is the shape it arrives in."""
    responses = spec["paths"][path]["post"]["responses"]
    for status in EXPECTED_ERROR_STATUSES:
        schema = responses[status]["content"]["application/json"]["schema"]
        assert schema["$ref"].endswith("/ProblemDetail"), f"{path} {status}"


def test_readiness_declares_its_503_as_a_readiness_body(spec: dict[str, Any]) -> None:
    """The one deliberate exception to "every failure is a problem document".

    A kubelet reads the status code and an operator reads the component list;
    neither wants a problem document, and §9's 503 (`no-verdict`) describes a
    failed *analysis*, not a probe.
    """
    responses = spec["paths"]["/v1/ready"]["get"]["responses"]
    schema = responses["503"]["content"]["application/json"]["schema"]
    assert schema["$ref"].endswith("/ReadyResponse")


# ── The artifact ──────────────────────────────────────────────────────────────


def test_the_spec_round_trips_through_the_committed_artifact(spec: dict[str, Any]) -> None:
    """Write ``docs/openapi.json`` and read it straight back.

    This is the ``make openapi`` artifact, written in exactly the form that
    target writes it. Round-tripping proves the document is JSON-serialisable —
    which is not free, since a stray non-serialisable default in a schema is
    only discovered on the way out — and leaves the committed file current.
    """
    rendered = json.dumps(spec, indent=2) + "\n"
    SPEC_PATH.parent.mkdir(parents=True, exist_ok=True)
    SPEC_PATH.write_text(rendered, encoding="utf-8")

    reloaded = json.loads(SPEC_PATH.read_text(encoding="utf-8"))
    assert reloaded == spec
